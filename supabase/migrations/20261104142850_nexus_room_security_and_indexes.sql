-- Tighten membership visibility and remove unused trigger-function RPC access.
drop policy if exists "members can view room membership" on public.room_members;
create policy "users can view their own room membership"
on public.room_members for select to authenticated
using (user_id = (select auth.uid()));

alter table private.room_join_attempts
  add column id bigint generated by default as identity primary key;

create index if not exists room_messages_sender_id_idx on public.room_messages(sender_id);
create index if not exists room_playback_updated_by_idx on public.room_playback(updated_by);
create index if not exists rooms_created_by_idx on public.rooms(created_by);

revoke all on function public.update_room_activity_from_child() from public, anon, authenticated;

create or replace function public.stamp_room_playback()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  new.updated_at := now();
  new.revision := old.revision + 1;
  return new;
end;
$$;
create trigger room_playback_stamp
before update on public.room_playback
for each row execute function public.stamp_room_playback();
revoke all on function public.stamp_room_playback() from public, anon, authenticated;
